# shellcheck shell=bash
# Защита от контаминации через открытый веб (подключается через `source`
# в run-pilot-ticket.sh, run-pilot-loop.sh и run-pilot-replay.sh).
#
# Репозиторий публичный: эталонная реализация (acceptance/reference-impl),
# acceptance-скрипты, спецификация и полные решения прошлых прогонов
# (docs/pilot-runs) доступны по сети. Харнесс при этом не запрещает агенту
# веб (WebFetch, WebSearch, curl из Bash), так что агент может скачать
# готовое решение, и результат прогона перестаёт быть чистым измерением
# языка — тот же класс утечки, что раунды 1-3 (CLAUDE.md, «Сначала
# пилот», пункт 4).
#
# Пока веб-доступ агента не закрыт, запуск требует явного подтверждения:
# PILOT_ACK_OPEN_WEB=1. Когда доступ будет закрыт (флаги в вызове
# `claude -p` и ограничение исходящей сети контейнера), этот файл и три
# вызова require_open_web_ack удаляются.

require_open_web_ack() {
  if [ "${PILOT_ACK_OPEN_WEB:-}" = "1" ]; then
    # Предупреждение один раз на цепочку replay -> loop -> ticket.
    if [ -z "${PILOT_OPEN_WEB_WARNED:-}" ]; then
      echo "ВНИМАНИЕ: веб агента открыт (PILOT_ACK_OPEN_WEB=1) — результаты прогона нельзя считать чистыми." >&2
      export PILOT_OPEN_WEB_WARNED=1
    fi
    return 0
  fi
  cat >&2 <<'MSG'
ОШИБКА: запуск заблокирован — у агента открыт веб.

Репозиторий публичный: эталонная реализация, acceptance-скрипты и решения
прошлых прогонов доступны по сети. Харнесс не запрещает агенту WebFetch,
WebSearch и исходящую сеть (curl), поэтому агент может скачать готовое
решение, и прогон перестаёт быть чистым измерением (CLAUDE.md, раздел
«Сначала пилот», пункт 4).

До полного прогона нужно:
  1. добавить --disallowedTools WebFetch,WebSearch в вызов claude -p
     (scripts/run-pilot-ticket.sh);
  2. ограничить исходящую сеть контейнера харнеса (allowlist реестров
     пакетов, нужных сборке кода тикета);
  3. проверить диагностическим прогоном по образцу трёх раундов.

Для отладки харнеса, где чистота результата не нужна, подтвердите явно:
  PILOT_ACK_OPEN_WEB=1 scripts/run-pilot-ticket.sh ...
MSG
  return 2
}
